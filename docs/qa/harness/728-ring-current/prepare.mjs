import {readFileSync,writeFileSync,mkdirSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {createRequire} from 'node:module';
import {execFileSync} from 'node:child_process';
import {resolve} from 'node:path';
const root=process.env.WC_RELEASE_ROOT,old=process.env.WC_RING_EXISTING,out=process.env.WC_QA_OUT;
if(!root||!old||!out)throw Error('Explicit ROOT/EXISTING/OUT required');
const hash=b=>createHash('sha256').update(b).digest('hex');
const bytes=readFileSync(old+'/ops_3.json'),sha=hash(bytes);
if(sha!=='ecbb146ddd9ecf3b6c3c46cc289245d92cbf246cf8225490eea70a9dee3ce1d9')throw Error('Immutable42 mismatch');
const original=JSON.parse(bytes),ops=original.filter(o=>o.type!=='image_import'),target=ops.find(o=>o.seq===61);
if(original.length!==42||ops.length!==41||target?.preset!=='normal:100:100:PB29:chisel')throw Error('Actual target61 guard');
let probe=readFileSync(old+'/probe.js','utf8');
// Preserve original controller's DEFAULT path; constructor option matches current Room.
const needle="{pageWidth:3508,pageHeight:2480,paper:'medium'}";
if(probe.split(needle).length!==2)throw Error('Original probe constructor drift');
probe=probe.replace(needle,"{pageWidth:3508,pageHeight:2480,paper:'medium',gradientFibres:true}");
new Function('return '+probe);
const files=execFileSync('git',['ls-files','apps/web/src/engine','packages/shared/src'],{cwd:root,encoding:'utf8'}).trim().split('\n');
const source=Object.fromEntries(files.map(f=>[f,hash(readFileSync(resolve(root,f)))]));
const head=execFileSync('git',['rev-parse','HEAD'],{cwd:root,encoding:'utf8'}).trim();
mkdirSync(out,{recursive:true});
const define=JSON.parse(readFileSync(old+'/build-passport.json')).define;
const {build}=createRequire(root+'/package.json')('esbuild');
await build({entryPoints:[root+'/apps/web/src/engine/index.ts'],outfile:out+'/current.mjs',bundle:true,platform:'browser',format:'esm',minify:false,define,alias:{'@grafetto/shared':root+'/packages/shared/src/index.ts'}});
writeFileSync(out+'/probe.js',probe);
writeFileSync(out+'/input.json',JSON.stringify({revision:head,policy:'DEFAULT',ops,operationTimeout:180000}));
writeFileSync(out+'/passport.json',JSON.stringify({head,source,journalSHA:sha,target:{id:target.id,seq:target.seq,preset:target.preset},original42:true,execution41:true,bundleSHA:hash(readFileSync(out+'/current.mjs')),probeSHA:hash(probe),options:{gradientFibres:true,phase:false,ADD:false},roi:{minX:910,minY:455,maxX:1264,maxY:721},limitations:['Endpoint material sums only; this probe does not expose pre-carry original-P mask.','Fixed signed original-P/wet-V profiles require separate stage capture; stale stage probe changes async/rebase flags and MUST NOT be substituted.','No device/Room/ACK/PASS asserted by preparation.']},null,2));
console.log(JSON.stringify({prepared:true,head,journalSHA:sha,bundleBytes:readFileSync(out+'/current.mjs').length}));
