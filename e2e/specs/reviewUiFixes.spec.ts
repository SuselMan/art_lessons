test('left-handed minimal UI animates its right edge and offers Fit after a pinch', async ({ page, context }) => {
  await page.addInitScript(() => {
    localStorage.setItem('al_device_type', 'tablet')
    localStorage.setItem('al_minimal_ui', 'true')
    localStorage.setItem('al_minimal_ui_tap', 'single')
    localStorage.setItem('al_handedness', 'left')
  })
  await createRoom(page); await waitForRoomReady(page)
  const quick = page.locator('[class*="quickSettingsBar"]').first()
  expect(await quick.evaluate(el => getComputedStyle(el).transitionProperty)).toContain('right')
  const cdp = await context.newCDPSession(page)
  await cdp.send('Emulation.setTouchEmulationEnabled', { enabled: true })
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: 650, y: 500 }] })
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
  await expect.poll(() => quick.evaluate(el => getComputedStyle(el).top)).toBe('0px')
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: 550, y: 400 }, { x: 750, y: 400 }] })
  for (let i = 1; i <= 5; i++) {
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: 550 - i * 10, y: 400 - i * 5 }, { x: 750 + i * 10, y: 400 + i * 5 }] })
  }
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
  await page.getByRole('button', { name: 'Fit', exact: true }).click()
  await expect.poll(() => page.evaluate(() => window.__roomStore!.getState().viewport.angle)).toBe(0)
  expect(await page.evaluate(() => window.__roomStore!.getState().viewport.zoom)).toBeLessThan(1)
  await cdp.detach()
})


