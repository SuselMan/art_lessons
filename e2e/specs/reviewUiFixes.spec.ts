import { expect, test, type Page } from '@playwright/test'
import { createRoom, waitForRoomReady } from '../support/room'

test.use({ actionTimeout: 15_000 })

async function settings(page: Page) {
  await page.getByRole('button', { name: 'Menu', exact: true }).click()
  await page.getByRole('menuitem', { name: 'Settings', exact: true }).click()
  return page.getByRole('dialog', { name: 'Settings', exact: true })
}

test('colour targets, native smudge default and direct numeric input', async ({ page }) => {
  await createRoom(page)
  await waitForRoomReady(page)
  await page.evaluate(() => window.__roomStore!.getState().setTool('shape'))
  const well = page.locator('aside[class*="toolbar"] button[aria-expanded]').first()
  const box = (await well.boundingBox())!
  await page.mouse.click(box.x + box.width / 2, box.y + 3)
  await expect.poll(() => page.evaluate(() => window.__roomStore!.getState().shapeSwatch)).toBe('stroke')
  await expect(page.getByRole('dialog', { name: 'Color', exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  await well.click()
  await expect.poll(() => page.evaluate(() => window.__roomStore!.getState().shapeSwatch)).toBe('fill')
  await page.keyboard.press('Escape')
  await page.evaluate(() => window.__roomStore!.getState().setTool('pencil'))
  const size = page.locator('[class*="quickSettingsBar"]').getByRole('textbox', { name: 'Size', exact: true })
  await size.fill('27'); await size.press('Enter')
  await expect.poll(() => page.evaluate(() => window.__roomStore!.getState().toolSettings.pencil.size)).toBe(27)
  await size.fill('91'); await size.press('Escape')
  await expect(size).toHaveValue('27px')
  await size.fill('0'); await size.press('Enter')
  await expect.poll(() => page.evaluate(() => window.__roomStore!.getState().toolSettings.pencil.size)).toBeGreaterThan(0)
  expect(await page.evaluate(() => window.__roomStore!.getState().toolSettings.smudge.opacity)).toBe(0.5)
})

test('settings use switches and segments, tooltip dismisses without closing settings, each tab resets', async ({ page }, info) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.addInitScript(() => { localStorage.setItem('al_theme', 'dark'); localStorage.setItem('al_debug_tools', 'true') })
  await createRoom(page); await waitForRoomReady(page)
  const dialog = await settings(page)
  const sound = dialog.getByRole('switch', { name: 'Sound', exact: true })
  await sound.click(); await expect(sound).toHaveAttribute('aria-checked', 'true')
  await expect(dialog.getByText('Sound', { exact: true })).toHaveCount(1)
  const segment = dialog.getByRole('radio', { name: 'Left-handed', exact: true })
  await segment.click()
  const selectedStyle = () => segment.evaluate(el => { const s = getComputedStyle(el); return { color: s.color, background: s.backgroundColor } })
  // A tablet keeps :hover after a tap. Selecting must remain accented before blur.
  const focusedStyle = await selectedStyle()
  await page.mouse.move(0, 0)
  await dialog.getByRole('heading', { name: 'Settings', exact: true }).click()
  expect(await selectedStyle()).toEqual(focusedStyle)
  const thumb = sound.locator('span').last()
  const darkThumb = await thumb.evaluate(el => getComputedStyle(el).backgroundColor)
  const darkSurface = await thumb.evaluate(el => { const probe = document.createElement('span'); probe.style.color = 'var(--color-surface)'; el.append(probe); const result = getComputedStyle(probe).color; probe.remove(); return result })
  expect(darkThumb).toBe(darkSurface)
  const resetStyle = () => dialog.getByRole('button', { name: 'Reset to defaults', exact: true }).evaluate(el => {
    const s = getComputedStyle(el)
    return [s.backgroundColor, s.color, s.fontSize, s.fontWeight, s.border, s.padding, s.minHeight, s.borderRadius]
  })
  const commonResetStyle = await resetStyle()
  await dialog.getByRole('button', { name: 'More information', exact: true }).focus()
  await expect(page.getByRole('tooltip')).toContainText('movable cluster')
  await page.keyboard.press('Escape')
  await expect(page.getByRole('tooltip')).toBeHidden()
  await expect(dialog).toBeVisible()
  await dialog.screenshot({ path: process.env.QA_SETTINGS_SCREENSHOT || info.outputPath('settings-general.png') })
  await dialog.getByRole('button', { name: 'Reset to defaults', exact: true }).click()
  await expect(sound).toHaveAttribute('aria-checked', 'false')
  await expect(dialog.getByRole('radio', { name: 'Right-handed', exact: true })).toHaveAttribute('aria-checked', 'true')
  await dialog.getByRole('tab', { name: 'Pen', exact: true }).click()
  expect(await resetStyle()).toEqual(commonResetStyle)
  await expect(dialog.getByRole('button', { name: 'Reset to defaults', exact: true })).toBeVisible()
  await dialog.getByRole('tab', { name: 'Tools', exact: true }).click()
  expect(await resetStyle()).toEqual(commonResetStyle)
  await expect(dialog.getByRole('button', { name: 'Reset to defaults', exact: true })).toBeVisible()
  await expect(dialog.getByRole('switch', { name: /students see/i })).toHaveCount(0)
  await page.setViewportSize({ width: 768, height: 1024 })
  await dialog.screenshot({ path: info.outputPath('settings-tools.png') })
  const overflow = await dialog.evaluate(el => el.scrollWidth > el.clientWidth)
  expect(overflow).toBe(false)
  await dialog.getByRole('tab', { name: 'Access', exact: true }).click()
  expect(await resetStyle()).toEqual(commonResetStyle)
  await expect(dialog.getByRole('button', { name: 'Reset to defaults', exact: true })).toBeVisible()
  await dialog.getByRole('tab', { name: 'Hotkeys', exact: true }).click()
  expect(await resetStyle()).toEqual(commonResetStyle)
  await expect(dialog.getByRole('button', { name: 'Reset to defaults', exact: true })).toBeVisible()
  await dialog.getByRole('tab', { name: 'Debug', exact: true }).click()
  expect(await resetStyle()).toEqual(commonResetStyle)
  await dialog.getByRole('tab', { name: 'General', exact: true }).click()
  await page.evaluate(async () => {
    const path = '/src/stores/settingsStore.ts'
    const { useSettingsStore } = await import(/* @vite-ignore */ path) as typeof import('../../apps/web/src/stores/settingsStore')
    useSettingsStore.getState().setTheme('light')
  })
  await expect.poll(() => thumb.evaluate(el => getComputedStyle(el).backgroundColor)).toBe('rgb(255, 255, 255)')
  expect(errors).toEqual([])
})

