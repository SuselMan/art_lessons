test('gallery displays author and license for a bundled brush', async ({ page }) => {
  await createRoom(page); await waitForRoomReady(page)
  const dialog = await settings(page)
  await dialog.getByRole('tab', { name: 'Tools', exact: true }).click()
  await dialog.getByRole('button', { name: /More brushes/ }).click()
  const gallery = page.getByRole('dialog').filter({ has: page.getByRole('button', { name: 'Purpose', exact: true }) })
  await page.route('**/api/brush-gallery?*', async route => {
    const url = new URL(route.request().url())
    if (url.searchParams.get('q') !== 'GDquest_Airbrush') return route.continue()
    return route.fulfill({ json: { items: [{ reference: 'brush:imported-aaaaaaaaaaaaaaaa@1', name: 'GDquest_Airbrush', source: 'gdquest-v7.bundle', role: 'drawing', category: 'paint', favorite: false }], total: 1, offset: 0, limit: 24 } })
  })
  await gallery.getByRole('searchbox', { name: 'Search brushes' }).fill('GDquest_Airbrush')
  const info = gallery.getByRole('button', { name: 'Brush credits and license' }).first()
  await expect(info).toBeVisible()
  await info.click()
  const credit = gallery.getByRole('region', { name: 'Brush credits and license' })
  await expect(credit).toContainText('GDQuest')
  await expect(credit.getByRole('link', { name: 'CC BY 4.0' })).toHaveAttribute('href', 'https://creativecommons.org/licenses/by/4.0/')
  await expect(credit).toContainText('Converted from the original brush for Grafetto.')
  if (process.env.QA_GALLERY_SCREENSHOT) await page.screenshot({ path: process.env.QA_GALLERY_SCREENSHOT })
  await credit.getByRole('button', { name: 'Close' }).click()
  await expect(credit).toHaveCount(0)
})
