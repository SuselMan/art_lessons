import { expect, test } from '@playwright/test'
import { createRoom, drawStroke, joinRoom, waitForOperations, waitForRoomReady } from '../support/room'

test('a frozen teacher board leaves personal work usable; personal freeze still blocks that student', async ({ page: teacher, browser }) => {
  const lesson = await createRoom(teacher)
  await waitForRoomReady(teacher)
  const context = await browser.newContext()
  try {
    const student = await context.newPage()
    await joinRoom(student, lesson, 'Alice')
    await teacher.getByRole('button', { name: /^Open Class/ }).click()
    await teacher.getByRole('button', { name: 'Freeze board', exact: true }).click()
    await expect.poll(() => student.evaluate(() => window.__roomStore!.getState().roomFrozen)).toBe(true)
    await drawStroke(teacher, [[400, 330], [700, 350]])
    await waitForOperations(teacher, 'stroke', 1)
    await teacher.getByRole('button', { name: 'New assignment', exact: true }).click()
    await teacher.getByRole('button', { name: 'Hand out', exact: true }).click()
    await student.waitForFunction(id => window.__roomStore!.getState().boardId !== id, lesson)
    await waitForRoomReady(student)
    expect(await student.evaluate(() => window.__roomStore!.getState().roomFrozen)).toBe(false)
    const personal = await student.evaluate(() => window.__roomStore!.getState().boardId)
    // The floating teacher-board preview covers the upper-left canvas after handout.
    await drawStroke(student, [[550, 420], [800, 440]])
    await waitForOperations(student, 'stroke', 1)
    await teacher.getByRole('button', { name: 'More actions', exact: true }).click()
    await teacher.getByRole('menuitem', { name: 'Freeze drawing', exact: true }).click()
    await expect(student.getByText('The project owner has paused your drawing.', { exact: true })).toBeVisible()
    await teacher.getByRole('button', { name: 'More actions', exact: true }).click()
    await teacher.getByRole('menuitem', { name: 'Unfreeze drawing', exact: true }).click()
    await waitForRoomReady(student)
    await student.getByRole('button', { name: /^Open Class/ }).click()
    await student.getByRole('button', { name: "Teacher's board", exact: true }).click()
    await expect.poll(() => student.evaluate(() => window.__roomStore!.getState().boardId)).toBe(lesson)
    await expect(student.getByText('The teacher has paused students’ drawing on this board.', { exact: true })).toBeVisible()
    await student.getByRole('button', { name: 'Assignment 1', exact: true }).click()
    await waitForRoomReady(student)
    expect(await student.evaluate(() => window.__roomStore!.getState().boardId)).toBe(personal)
    await student.reload()
    await student.locator('form input[type="text"]').fill('Alice')
    await student.locator('form button[type="submit"]').click()
    await student.waitForFunction(() => !!window.__roomStore?.getState().lessonId)
    if (await student.evaluate(() => window.__roomStore!.getState().boardId) !== personal) {
      const mine = student.getByRole('region', { name: 'My boards' })
      if (!await mine.isVisible()) await student.getByRole('button', { name: /^Open Class/ }).click()
      await mine.getByRole('button', { name: 'Assignment 1', exact: true }).click()
    }
    await waitForRoomReady(student)
    expect(await student.evaluate(() => window.__roomStore!.getState().roomFrozen)).toBe(false)
    await drawStroke(student, [[420, 420], [720, 440]])
    await waitForOperations(student, 'stroke', 2)
  } finally { await context.close().catch(() => {}) }
})
