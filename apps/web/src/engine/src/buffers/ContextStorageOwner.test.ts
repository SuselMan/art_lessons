import { expect, it, vi } from 'vitest'
import { MockGL } from '../../testing/mockGL'
import { AccumulationBuffer } from './AccumulationBuffer'
import { RibbonScratchPool } from './RibbonScratchPool'
import { attachAccumStorage, forgetAccumStorage, materializeAccumStorage, releaseAccumLease, releaseAccumReservation, reserveAccumStorage, snapshotAccumStorage, validateAccumReservation } from './ContextStorageOwner'

function setup(limitBytes = Infinity) {
  const mock = new MockGL(), gl = mock as unknown as WebGLRenderingContext
  attachAccumStorage(gl, { limitBytes })
  return { mock, gl }
}
it('transfers a partial promise exactly once and rejects unknown, foreign and expired tokens', () => {
  const { gl } = setup(128), other = setup().gl, ticket = reserveAccumStorage(gl, 128)
  const lease = materializeAccumStorage(gl, ticket, 64)
  expect(snapshotAccumStorage(gl)).toMatchObject({ residentBytes: 64, reservedBytes: 64, complete: false })
  expect(() => validateAccumReservation(other, ticket, 1)).toThrow('Invalid')
  expect(() => validateAccumReservation(gl, { kind: 'context-storage-reservation' }, 0)).toThrow('Invalid')
  releaseAccumReservation(ticket); releaseAccumReservation(ticket)
  expect(() => materializeAccumStorage(gl, ticket, 1)).toThrow('Invalid')
  releaseAccumLease(lease, true); releaseAccumLease(lease, true)
  expect(snapshotAccumStorage(gl).residentBytes).toBe(0)
  const stale = reserveAccumStorage(gl, 32)
  forgetAccumStorage(gl)
  const fresh = new AccumulationBuffer(gl, 4, 4)
  expect(() => validateAccumReservation(gl, stale, 0)).toThrow('Invalid')
  releaseAccumReservation(stale)
  expect(snapshotAccumStorage(gl)).toMatchObject({ residentBytes: 64, reservedBytes: 0, limitBytes: 128 })
  fresh.destroy()
})
it('denies actual allocations before GL and preserves pool idle storage until trim', () => {
  const { mock, gl } = setup(64), pool = new RibbonScratchPool(gl)
  const buffer = pool.acquire(4, 4)
  pool.release(buffer)
  const create = vi.spyOn(mock, 'createTexture')
  expect(pool.acquire(4, 4)).toBe(buffer)
  expect(create).not.toHaveBeenCalled()
  expect(() => new AccumulationBuffer(gl, 1, 1)).toThrow('admission')
  expect(create).not.toHaveBeenCalled()
  expect(snapshotAccumStorage(gl).residentBytes).toBe(64)
  pool.release(buffer); pool.trimFree()
  expect(snapshotAccumStorage(gl).residentBytes).toBe(0)
  pool.destroy()
})
it('failed constructor preserves externally owned promise and primary error', () => {
  const { mock, gl } = setup(64), ticket = reserveAccumStorage(gl, 64), primary = new Error('storage primary')
  vi.spyOn(mock, 'texImage2D').mockImplementationOnce(() => { throw primary })
  vi.spyOn(mock, 'deleteTexture').mockImplementationOnce(() => { throw new Error('cleanup secondary') })
  expect(() => new AccumulationBuffer(gl, 4, 4, 'nearest', 'premultiplied-rgba8', ticket)).toThrow(primary)
  expect(snapshotAccumStorage(gl)).toMatchObject({ residentBytes: 64, orphanBytes: 64, reservedBytes: 64 })
  validateAccumReservation(gl, ticket, 64)
  releaseAccumReservation(ticket)
  expect(() => reserveAccumStorage(gl, 1)).toThrow('admission')
  AccumulationBuffer.forgetContextStorage(gl)
  expect(snapshotAccumStorage(gl)).toMatchObject({ residentBytes: 0, orphanBytes: 0 })
})
it('FBO deletion failure does not charge deleted texture bytes; failed destroy keeps texture orphan charged', () => {
  const { mock, gl } = setup(), buffer = new AccumulationBuffer(gl, 4, 4)
  const primary = new Error('delete texture')
  const delFbo = vi.spyOn(mock, 'deleteFramebuffer')
  vi.spyOn(mock, 'deleteTexture').mockImplementationOnce(() => { throw primary })
  expect(() => buffer.destroy()).toThrow(primary)
  expect(delFbo).toHaveBeenCalledTimes(1)
  buffer.destroy()
  expect(snapshotAccumStorage(gl)).toMatchObject({ residentBytes: 64, orphanBytes: 64 })
  AccumulationBuffer.forgetContextStorage(gl)
  const fresh = new AccumulationBuffer(gl, 4, 4)
  delFbo.mockImplementationOnce(() => { throw new Error('FBO only') })
  expect(() => fresh.destroy()).toThrow('FBO only')
  expect(snapshotAccumStorage(gl).residentBytes).toBe(0)
})
it('reports preexisting GL error before allocation and detects void storage errors without consuming external promise', () => {
  const { mock, gl } = setup(64), ticket = reserveAccumStorage(gl, 64)
  const create = vi.spyOn(mock, 'createTexture'), error = vi.spyOn(mock, 'getError')
  error.mockReturnValueOnce(1280)
  expect(() => new AccumulationBuffer(gl, 4, 4, 'nearest', 'premultiplied-rgba8', ticket)).toThrow('preexisting GL error 1280')
  expect(create).not.toHaveBeenCalled()
  error.mockReturnValueOnce(0).mockReturnValueOnce(1285)
  expect(() => new AccumulationBuffer(gl, 4, 4, 'nearest', 'premultiplied-rgba8', ticket)).toThrow('texture allocation GL error 1285')
  expect(snapshotAccumStorage(gl)).toMatchObject({ residentBytes: 0, reservedBytes: 64 })
  const buffer = new AccumulationBuffer(gl, 4, 4, 'nearest', 'premultiplied-rgba8', ticket)
  releaseAccumReservation(ticket)
  expect(snapshotAccumStorage(gl)).toMatchObject({ residentBytes: 64, reservedBytes: 0 })
  buffer.destroy()
})
it('requires resize peak headroom while retaining the old allocation on denial', () => {
  const { gl } = setup(128), old = new AccumulationBuffer(gl, 4, 4)
  expect(() => new AccumulationBuffer(gl, 5, 4)).toThrow('admission')
  expect(old.storageByteLength).toBe(64)
  const replacement = new AccumulationBuffer(gl, 4, 4)
  expect(snapshotAccumStorage(gl).residentBytes).toBe(128)
  old.destroy(); expect(snapshotAccumStorage(gl).residentBytes).toBe(64)
  replacement.destroy()
})
it('adopts preexisting actual context charges, rejects incompatible policies and snapshots have no mutable owner', () => {
  const mock = new MockGL(), gl = mock as unknown as WebGLRenderingContext
  const before = new AccumulationBuffer(gl, 4, 4)
  expect(() => attachAccumStorage(gl, { limitBytes: 63 })).toThrow('Existing')
  attachAccumStorage(gl, { limitBytes: 128 }); attachAccumStorage(gl, { limitBytes: 128 })
  expect(() => attachAccumStorage(gl, { limitBytes: 256 })).toThrow('mismatch')
  const snapshot = snapshotAccumStorage(gl)
  expect(Object.isFrozen(snapshot)).toBe(true)
  expect(snapshot.residentBytes).toBe(64)
  before.destroy()
})
it('checks first mip headroom before GL and conservatively retains failed void mip storage until texture deletion', () => {
  const limited = setup(64), limitedBuffer = new AccumulationBuffer(limited.gl, 4, 4)
  const generate = vi.spyOn(limited.mock, 'generateMipmap')
  expect(() => limitedBuffer.ensureMipmaps()).toThrow('admission')
  expect(generate).not.toHaveBeenCalled()
  limitedBuffer.destroy()
  const { mock, gl } = setup(84), buffer = new AccumulationBuffer(gl, 4, 4)
  const error = vi.spyOn(mock, 'getError')
  error.mockReturnValueOnce(0).mockReturnValueOnce(1285)
  expect(() => buffer.ensureMipmaps()).toThrow('mipmap allocation GL error 1285')
  expect(snapshotAccumStorage(gl)).toMatchObject({ residentBytes: 84, reservedBytes: 0, orphanBytes: 0 })
  buffer.ensureMipmaps()
  expect(snapshotAccumStorage(gl).residentBytes).toBe(84)
  buffer.destroy()
  expect(snapshotAccumStorage(gl).residentBytes).toBe(0)
})
it('does not retain unknown storage when texture creation fails or when partial texture deletion succeeds', () => {
  const { mock, gl } = setup()
  const allocator = gl as unknown as { createTexture(): WebGLTexture | null }
  vi.spyOn(allocator, 'createTexture').mockReturnValueOnce(null)
  expect(() => new AccumulationBuffer(gl, 4, 4)).toThrow('texture allocation failed')
  expect(snapshotAccumStorage(gl)).toMatchObject({ residentBytes: 0, reservedBytes: 0, orphanBytes: 0 })
  vi.spyOn(mock, 'framebufferTexture2D').mockImplementationOnce(() => { throw new Error('attach primary') })
  vi.spyOn(mock, 'deleteFramebuffer').mockImplementationOnce(() => { throw new Error('FBO secondary') })
  expect(() => new AccumulationBuffer(gl, 4, 4)).toThrow('attach primary')
  expect(snapshotAccumStorage(gl)).toMatchObject({ residentBytes: 0, reservedBytes: 0, orphanBytes: 0 })
})
it('forgets stale ownership without deleting old names and keeps diagnostics free of GL queries', () => {
  const { mock, gl } = setup(128), stale = new AccumulationBuffer(gl, 4, 4)
  AccumulationBuffer.forgetContextStorage(gl)
  const fresh = new AccumulationBuffer(gl, 4, 4)
  const del = vi.spyOn(mock, 'deleteTexture'), query = vi.spyOn(mock, 'getError')
  stale.destroy()
  snapshotAccumStorage(gl); AccumulationBuffer.contextStorageByteLength(gl)
  expect(del).not.toHaveBeenCalled(); expect(query).not.toHaveBeenCalled()
  expect(snapshotAccumStorage(gl).residentBytes).toBe(64)
  fresh.destroy()
  expect(snapshotAccumStorage(gl).residentBytes).toBe(0)
})

it('rejects a foreign constructor ticket before even querying the target GL context', () => {
  const { mock, gl } = setup(), other = setup().gl, ticket = reserveAccumStorage(other, 64)
  const lost = vi.spyOn(mock, 'isContextLost'), error = vi.spyOn(mock, 'getError'), create = vi.spyOn(mock, 'createTexture')
  expect(() => new AccumulationBuffer(gl, 4, 4, 'nearest', 'premultiplied-rgba8', ticket)).toThrow('reservation')
  expect(lost).not.toHaveBeenCalled(); expect(error).not.toHaveBeenCalled(); expect(create).not.toHaveBeenCalled()
  validateAccumReservation(other, ticket, 64)
  releaseAccumReservation(ticket)
})

it('retries unconfirmed mip allocations with cold error checks without charging or reserving again', () => {
  const { mock, gl } = setup(84), buffer = new AccumulationBuffer(gl, 4, 4)
  const error = vi.spyOn(mock, 'getError'), generate = vi.spyOn(mock, 'generateMipmap')
  for (let retry = 0; retry < 2; retry++) {
    error.mockReturnValueOnce(0).mockReturnValueOnce(1285)
    expect(() => buffer.ensureMipmaps()).toThrow('mipmap allocation GL error 1285')
    expect(snapshotAccumStorage(gl)).toMatchObject({ residentBytes: 84, reservedBytes: 0 })
  }
  expect(generate).toHaveBeenCalledTimes(2)
  expect(buffer.ensureMipmaps()).toBe(true)
  expect(generate).toHaveBeenCalledTimes(3)
  expect(buffer.ensureMipmaps()).toBe(true)
  expect(generate).toHaveBeenCalledTimes(3)
  expect(snapshotAccumStorage(gl)).toMatchObject({ residentBytes: 84, reservedBytes: 0 })
  buffer.destroy()
})
it('restores the historical default framebuffer on constructor failure even when cleanup deletion throws', () => {
  const { mock, gl } = setup(), primary = new Error('attach primary')
  vi.spyOn(mock, 'framebufferTexture2D').mockImplementationOnce(() => { throw primary })
  const deleteFbo = vi.spyOn(mock, 'deleteFramebuffer').mockImplementationOnce(() => { throw new Error('delete FBO') })
  const deleteTexture = vi.spyOn(mock, 'deleteTexture').mockImplementationOnce(() => { throw new Error('delete texture') })
  const bind = vi.spyOn(mock, 'bindFramebuffer')
  expect(() => new AccumulationBuffer(gl, 4, 4)).toThrow(primary)
  expect(deleteFbo).toHaveBeenCalledTimes(1); expect(deleteTexture).toHaveBeenCalledTimes(1)
  expect(bind).toHaveBeenLastCalledWith(gl.FRAMEBUFFER, null)
  expect(snapshotAccumStorage(gl)).toMatchObject({ residentBytes: 64, orphanBytes: 64, reservedBytes: 0 })
  AccumulationBuffer.forgetContextStorage(gl)
})
