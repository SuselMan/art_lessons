import * as Sentry from '@sentry/react'

/** (#480, трек #314 §1) Сообщает о нарушенном инварианте — о том, что пошло
 *  не так, ничего при этом не бросив.
 *
 *  Sentry здесь ловит исключения (см. lib/sentry.ts), и это покрывает ровно
 *  тот класс поломок, к которому оба бага урока 21.08 не относились. #477 был
 *  осиротевшей записью, из-за которой клиент до конца сессии молча перестал
 *  печь снапшоты; #479 — чекпойнтом, снятым поверх неучтённой краски. Оба
 *  нарушали контракт, записанный прозой в докстринге, оба не бросили ничего,
 *  и оба были невидимы: в Sentry пусто, урок сломан.
 *
 *  При этом код в обоих случаях **знал**, что что-то не так, и говорил об
 *  этом в `console.warn` — то есть в место, которого на планшете
 *  преподавателя не существует. Задача этого модуля — дать тем же местам
 *  адресата.
 *
 *  Три свойства, без которых это стало бы шумом, который перестают читать:
 *
 *  - **Дедуп по имени.** Одно и то же нарушение за одну сессию сообщается
 *    один раз. Почти все здешние инварианты живут в горячем цикле (приход
 *    операции, граница чекпойнта), и «сообщать каждый раз» означает тысячи
 *    событий об одном факте.
 *  - **Повторы не выбрасываются молча.** Каждое срабатывание оставляет
 *    хлебную крошку, а счётчик уезжает в контекст — потому что «случилось
 *    однажды» и «случается непрерывно» это разные новости, а второе как раз
 *    и описывает залипшее состояние. Тот же приём, что у reportRestore.ts
 *    (#474): крошка всегда, событие — когда есть что сказать.
 *  - **`warning`, не `error`.** Это не отказ, это состояние, которое станет
 *    отказом, если его не заметить.
 *
 *  Содержимое холста, имена и почта сюда не попадают и попадать не должны:
 *  контекст — это счётчики, seq, идентификаторы слоёв и причины. См. #323. */

/** Одна категория на все инварианты: в Sentry крошки фильтруются по ней, и
 *  «покажи всё, что этот клиент считал неправильным» должно быть одним
 *  фильтром, а не перечислением имён. */
const BREADCRUMB_CATEGORY = 'invariant'

/** Сколько раз каждый инвариант сработал за сессию, включая подавленные
 *  дедупом повторы. */
const counts = new Map<string, number>()

/** Имена, о которых уже отчитались. Отдельно от `counts`: счётчик растёт
 *  всегда, отчёт случается один раз. */
const reported = new Set<string>()

export interface InvariantContext {
  [key: string]: string | number | boolean | null | undefined
}

/** `name` — стабильный короткий идентификатор, по которому это группируется в
 *  Sentry на протяжении месяцев. Не сообщение для человека: подробности
 *  уезжают в `context`, а имя должно пережить переформулировку. */
export function reportInvariant(name: string, context: InvariantContext = {}): void {
  const seen = (counts.get(name) ?? 0) + 1
  counts.set(name, seen)
  // Консоль остаётся: при отладке с открытым девтулзом она полезнее Sentry,
  // и именно она показывает повторы, которые дедуп ниже съедает.
  console.warn(`[invariant] ${name}`, { ...context, seen })
  Sentry.addBreadcrumb({ category: BREADCRUMB_CATEGORY, level: 'warning', message: name, data: { ...context, seen } })
  if (reported.has(name)) return
  reported.add(name)
  Sentry.captureMessage(name, {
    level: 'warning',
    tags: { invariant: name },
    extra: { ...context, seen, invariantCounts: countsSnapshot() },
  })
}

/** Все счётчики на текущий момент — цепляется к каждому отчёту, чтобы по
 *  одному событию было видно, что ещё происходит в этой сессии рядом. Часто
 *  это и есть ответ: «водяной знак застрял» само по себе загадка, а вместе с
 *  «и до этого сорок раз был разрыв потока» — уже нет. */
export function countsSnapshot(): Record<string, number> {
  return Object.fromEntries(counts)
}

/** Тестовый шов: дедуп и счётчики живут на модуле, а модуль в vitest один на
 *  весь файл. Без сброса второй тест наблюдал бы решения первого. */
export function _resetInvariants(): void {
  counts.clear()
  reported.clear()
}
