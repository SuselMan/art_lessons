import type { Server } from 'socket.io'

/** (#504) Разорвать соединения так, чтобы клиенты переподключились сами.
 *
 *  Разница между этим вызовом и `io.disconnectSockets(true)`, который стоял
 *  здесь раньше, — не стилистическая: от неё зависит, увидит ли ученик свою
 *  комнату снова без перезагрузки страницы.
 *
 *  `disconnectSockets` вежлив. Он отправляет клиенту пакет DISCONNECT, то есть
 *  говорит «мы расстаёмся», — а решение сервера расстаться socket.io-client не
 *  переигрывает: reason приезжает как `io server disconnect`, менеджер ставит
 *  `skipReconnect`, `socket.active` становится false, и попыток
 *  переподключения не будет уже никогда — до перезагрузки вкладки. Деплой у
 *  нас на каждый пуш в `main`, так что каждый деплой оставлял всех, кто в этот
 *  момент рисовал, с висящим «Нет связи — переподключение…», в котором никакого
 *  переподключения не происходило.
 *
 *  Закрытие на уровне транспорта клиент читает как обыкновенный обрыв
 *  (`transport close`) и переподключается с обычным бэкоффом, пока не
 *  поднимется новый контейнер. Заодно `engine.close()` перестаёт принимать
 *  новые соединения — ровно то, чего хочет первый шаг выключения: оборвать
 *  приток операций, пока мы дожидаемся записи уже принятых.
 *
 *  Отдельным модулем ради шва: `index.ts` в тесте не поднять (он на верхнем
 *  уровне вешает обработчики сигналов и слушает порт), а проверять тут нужно
 *  ровно одно утверждение — что живой клиент после этого вызова приходит
 *  обратно сам. Именно оно и было неверным. */
export function disconnectAllClients(io: Server): void {
  io.engine.close()
}
