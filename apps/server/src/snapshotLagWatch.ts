import { SNAPSHOT_SEQ_INTERVAL } from '@grafetto/shared'

/** (#480, трек #314 §1) Сторож отставания снапшотов: замечает, что комната
 *  перестала получать снапшоты, пока в ней ещё идёт урок.
 *
 *  Клиенты пекут снапшот раз в SNAPSHOT_SEQ_INTERVAL операций, и до 21.08
 *  ничто не проверяло, что это вообще происходит. В комнате `Igy2jy_i`
 *  выпечка встала на seq 1500 из-за застрявшей записи в водяном знаке (#477),
 *  урок шёл ещё полчаса и набрал 1428 операций, не покрытых ничем. Каждый
 *  перезаход платил за это реплеем всей этой тысячи поверх 5.8 МБ снапшотов,
 *  под конец перестал доходить до конца вовсе — и ни одного события об этом
 *  не возникло, потому что события такого рода не существовало: остановка
 *  периодического действия не бросает исключение, она просто не происходит.
 *
 *  **Меряем не разницу seq, а число непокрытых операций.** Соблазн вычесть
 *  «последний seq снапшота» из «последнего seq комнаты» здесь ловушка, о
 *  которой прямо предупреждает `coveredSeqByLayer` в rooms.ts: покрытие —
 *  величина по слоям, и всякая попытка свернуть её в одно число это способ
 *  счесть покрытым слой, который никто не снапшотил (так потерялось
 *  содержимое в #369). Поэтому берём тот же честный ответ по слоям, что и
 *  `getRoomSnapshot`: сколько операций пришлось бы проиграть входящему
 *  заново. Это не прокси — это ровно та цена, которую платит человек,
 *  перезаходящий в комнату.
 *
 *  Порог по умолчанию — три интервала выпечки. На данных 21.08 сторож
 *  сработал бы около 20:05, за 26 минут до того, как урок стал нерабочим. */
export const SNAPSHOT_LAG_THRESHOLD = 3 * SNAPSHOT_SEQ_INTERVAL

// `type`, а не `interface`, и это не вкусовщина: неявную индексную сигнатуру
// TypeScript выдаёт псевдониму объектного типа и не выдаёт интерфейсу, а без
// неё это не уезжает в `extra` у Sentry (`Record<string, unknown>`) иначе как
// через каст.
export type RoomBacklog = {
  roomId: string
  /** Живых участников. Пустая комната не печёт снапшоты по построению, и
   *  отставание в ней ничего не значит. */
  participants: number
  /** Последний выданный seq — для отчёта, не для решения. */
  latestSeq: number
  /** Сколько операций пришлось бы проиграть входящему в комнату заново. */
  uncoveredOps: number
}

export interface SnapshotLagWatch {
  /** `null`, когда сообщать не о чем. Иначе — то, о чём стоит отчитаться. */
  observe(backlog: RoomBacklog): RoomBacklog | null
  /** Комната вытеснена из памяти: забыть про неё, иначе набор растёт с числом
   *  комнат за всё время жизни процесса, а не с числом живых. */
  forget(roomId: string): void
}

export function createSnapshotLagWatch(threshold = SNAPSHOT_LAG_THRESHOLD): SnapshotLagWatch {
  // Отставание, при котором по этой комнате последний раз отчитались.
  const reportedAt = new Map<string, number>()

  return {
    observe(backlog) {
      const { roomId, participants, uncoveredOps } = backlog
      if (participants < 1 || uncoveredOps < threshold) {
        // Ниже порога — снимаем отметку, чтобы следующее сваливание
        // отчиталось как новое, а не молчало из-за старой записи.
        reportedAt.delete(roomId)
        return null
      }
      const previous = reportedAt.get(roomId)
      // Пока отставание не удвоилось с прошлого отчёта, повторяться незачем:
      // урок идёт, порог проверяется каждые сто операций, и без этого одна
      // застрявшая комната дала бы по событию каждые пару минут до конца
      // занятия. Удвоение же — новость: значит не просто не чинится, а
      // расходится быстрее, чем росло до сих пор.
      if (previous !== undefined && uncoveredOps < previous * 2) return null
      reportedAt.set(roomId, uncoveredOps)
      return backlog
    },

    forget(roomId) {
      reportedAt.delete(roomId)
    },
  }
}
