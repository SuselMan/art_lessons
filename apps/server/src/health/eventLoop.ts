import { type EventLoopUtilization, monitorEventLoopDelay, performance } from 'node:perf_hooks'

/** (#324, трек #314 §9) Задержка событийного цикла — «процессор кончился» на
 *  языке Node.
 *
 *  Из трёх стен, в которые может упереться коробка, эта единственная не имела
 *  прибора вовсе. Память и диск отвечают на вопрос «сколько уроков может быть
 *  открыто»; нагрузку же создают те, где прямо сейчас **рисуют**: каждый штрих
 *  надо принять, сжать, разослать всем участникам и записать в базу. Всё это
 *  делает один поток, и когда он перестаёт успевать, ни куча, ни диск об этом
 *  не сообщают — растёт только время между «событие готово» и «событие
 *  обработано». Оно и меряется здесь.
 *
 *  Почему не загрузка CPU: сервер на двух ядрах может показывать 50% и при
 *  этом стоять колом, потому что занято одно ядро — то, на котором крутится
 *  JS. Величины ниже описывают состояние самого цикла, а не то, чем занято
 *  железо.
 *
 *  Величин две, и главная из них — `utilization`, а не задержка. Это вывод
 *  нагрузочного прогона 10.08, а не соображение: при 400 рисующих комнатах
 *  подтверждение штриха уходило за 8.9 с — урок сломан полностью, — а p99
 *  задержки показывал 35 мс при пороге 200. Перегрузка здесь выглядит не как
 *  долгие залипания, а как очередь: тиков много, каждый короткий. Задержка
 *  оставлена, потому что ловит другую беду — одну долгую синхронную операцию,
 *  которая заморозит всех при низкой общей загрузке.
 *
 *  **Окно, а не «с начала процесса».** Гистограмма за весь аптайм бесполезна
 *  для тревоги: один просевший кадр в прошлый вторник навсегда испортит
 *  максимум и никогда не расскажет о сегодняшнем. Поэтому раз в
 *  `EVENT_LOOP_WINDOW_SECONDS` окно закрывается, попадает в `lastWindow` и
 *  сбрасывается.
 *
 *  Сброс делает таймер, а **не чтение**: `/api/health` — это GET, и
 *  наблюдение, меняющее наблюдаемое, — ловушка, в которую попадают ровно один
 *  раз и надолго. Два читателя (проба и человек) иначе делили бы окно пополам
 *  и оба видели бы не то. */
export type EventLoopSnapshot = {
  /** Медиана задержки в закрытом окне. Говорит о нормальной жизни. */
  p50Ms: number
  /** Хвост в закрытом окне. Именно он ощущается как рывки. */
  p99Ms: number
  /** Худшая единичная задержка в закрытом окне. */
  maxMs: number
  /** Худшее `maxMs` за весь аптайм — чтобы ночной всплеск не пропал к утру. */
  worstMs: number
  /** Доля времени в окне, которую цикл был занят делом, от 0 до 1.
   *
   *  Здесь живёт настоящая тревога, и это вывод из нагрузочного прогона, а не
   *  предпочтение. Задержка (`p99Ms`) меряет длину **одного** залипания, а
   *  этот сервер под перегрузкой залипает не надолго, а часто: тиков много,
   *  каждый короткий, растёт очередь. Замер 10.08 на двух ядрах: при 400
   *  рисующих комнатах подтверждение штриха уходило за 8.9 с, то есть урок
   *  сломан полностью, — а `p99Ms` показывал 35 мс при пороге 200. Тревога,
   *  поставленная на задержку, не сработала бы ни разу за всю аварию.
   *
   *  Утилизация же ведёт себя ровно как надо: она упирается в единицу тогда,
   *  когда циклу перестаёт хватать времени, независимо от того, одним длинным
   *  куском он занят или тысячей коротких. */
  utilization: number
  windowSeconds: number
}

const NS_PER_MS = 1e6

/** Разрешение опроса — оно же пол показаний, и это не деталь реализации.
 *
 *  `monitorEventLoopDelay` заводит таймер на каждые `resolution` мс и
 *  записывает **полный** промежуток до срабатывания, а не превышение над ним.
 *  Поэтому простаивающий сервер честно рапортует ≈`resolution`: замер на
 *  холостом контейнере дал p50 20.2 при resolution 20. Оставить как есть
 *  значило бы сдвинуть все пороги на эту величину — «p99 = 50 мс» означало бы
 *  настоящие 30, и тревога уходила бы раньше, чем что-то произошло.
 *
 *  Поэтому ниже пол вычитается, а число называется тем, чем является:
 *  задержкой сверх ожидаемой. 10 мс, а не 20, чтобы пол был мельче и вычитание
 *  меньше огрубляло хвост. */
const RESOLUTION_MS = 10

const WINDOW_SECONDS = readWindowSeconds()

/** Порог письма. 50 мс на p99 — это уже три пропущенных кадра подряд: рывок
 *  видно, но урок идёт. */
export const EVENT_LOOP_WARN_MS = 50

/** Порог тревоги по задержке. 200 мс взяты не с потолка: это ровно тот потолок
 *  залипания главного потока, который #324 объявил приёмочным для клиента.
 *
 *  Оставлен, но перестал быть главным: прогон 10.08 показал, что этот сервер
 *  умеет умереть, не превысив его (см. `utilization`). Он ловит другой класс
 *  беды — одну долгую синхронную операцию, — и этот класс никуда не делся. */
export const EVENT_LOOP_CRITICAL_MS = 200

/** Порог письма по утилизации. 0.7 — это запас: замер даёт приемлемые задержки
 *  примерно до этой отметки, а дальше начинается участок, на котором каждая
 *  следующая комната дороже предыдущей. */
export const EVENT_LOOP_WARN_UTILIZATION = 0.7

/** Порог тревоги по утилизации. 0.9 выбрано по форме излома, а не круглостью:
 *  переход от «250 комнат, подтверждение 48 мс» к «400 комнат, подтверждение
 *  8.9 с» занимает считаные проценты загрузки, потому что это не деградация, а
 *  насыщение очереди. Ждать 0.99 значит узнать об аварии от учителя. */
export const EVENT_LOOP_CRITICAL_UTILIZATION = 0.9

function readWindowSeconds(): number {
  const raw = process.env.EVENT_LOOP_WINDOW_SECONDS
  if (raw === undefined) return 60
  const parsed = Number(raw)
  if (!Number.isFinite(parsed) || parsed < 1) {
    console.error(`EVENT_LOOP_WINDOW_SECONDS=${raw} is not a positive number of seconds — using 60`)
    return 60
  }
  return parsed
}

let histogram: ReturnType<typeof monitorEventLoopDelay> | null = null
let lastWindow: EventLoopSnapshot | null = null
let worstMs = 0
// Утилизация в Node накопительная с момента старта, поэтому окно берётся
// разностью с предыдущим отсчётом — иначе первые спокойные часы навсегда
// размажут любую сегодняшнюю перегрузку.
let previousUtilization: EventLoopUtilization | null = null

/** Запускается один раз при старте (index.ts). Идемпотентна: повторный вызов
 *  ничего не пересоздаёт — иначе тест, поднимающий приложение дважды, тихо
 *  оставил бы два таймера, и окна начали бы закрывать друг друга. */
export function startEventLoopMonitor(): void {
  if (histogram) return
  histogram = monitorEventLoopDelay({ resolution: RESOLUTION_MS })
  histogram.enable()

  const timer = setInterval(() => {
    if (!histogram) return
    const maxMs = excessMs(histogram.max)
    // `max` у пустой гистограммы — огромное число (так libuv сообщает «нет
    // данных»), и без этой отсечки первое же окно на простаивающем сервере
    // отправило бы письмо о катастрофе.
    const usable = Number.isFinite(maxMs) && histogram.count > 0
    // Худшее обновляется ДО сборки окна, иначе всплеск не попадает в тот
    // самый отчёт, ради которого «худшее за всё время» и заведено: окно с
    // рекордом сообщало бы предыдущий рекорд, а к следующему окну повод уже
    // забыт.
    if (usable && maxMs > worstMs) worstMs = maxMs
    const current = performance.eventLoopUtilization()
    const window = previousUtilization === null
      ? current
      : performance.eventLoopUtilization(current, previousUtilization)
    previousUtilization = current
    lastWindow = {
      p50Ms: usable ? excessMs(histogram.percentile(50)) : 0,
      p99Ms: usable ? excessMs(histogram.percentile(99)) : 0,
      maxMs: usable ? maxMs : 0,
      worstMs,
      utilization: Math.round(window.utilization * 1000) / 1000,
      windowSeconds: WINDOW_SECONDS,
    }
    histogram.reset()
  }, WINDOW_SECONDS * 1000)
  // Без unref таймер держал бы процесс живым и превращал штатное завершение в
  // зависание — в тестах это выглядит как «сюита не заканчивается».
  timer.unref()
}

/** Наносекунды из гистограммы — в миллисекунды задержки **сверх** ожидаемой.
 *  Отрицательное срезается в ноль: таймер, сработавший чуть раньше срока, —
 *  это не «опережение», а шум округления, и пускать его в перцентили значит
 *  занижать их тем сильнее, чем спокойнее сервер. */
function excessMs(nanoseconds: number): number {
  const ms = nanoseconds / NS_PER_MS - RESOLUTION_MS
  return Math.round(Math.max(0, ms) * 10) / 10
}

/** `null`, пока не закрылось ни одного окна — то есть первые
 *  `windowSeconds` после старта. Именно `null`, а не нули: «ещё не мерили» и
 *  «намерили ноль» — разные ответы, и второй из них здесь был бы ложью,
 *  которую мониторинг принял бы за здоровье. */
export function readEventLoop(): EventLoopSnapshot | null {
  return lastWindow
}

export type EventLoopPressure = 'ok' | 'warn' | 'critical' | 'unknown'

/** Худшее из двух суждений, а не одно.
 *
 *  Две величины ловят две разные беды, и ни одна не покрывает другую:
 *  утилизация видит насыщение (много коротких тиков, растущая очередь —
 *  именно так этот сервер и умирает под нагрузкой), задержка видит одну долгую
 *  синхронную операцию, которая при низкой общей загрузке заморозит всех
 *  разом. Брать только утилизацию значило бы пропустить второе. */
export function eventLoopPressureOf(snapshot: EventLoopSnapshot | null): EventLoopPressure {
  // Отсутствие данных — не тревога: сразу после рестарта их честно нет, а
  // рестарт и так виден по `uptimeSeconds`. Тревожить письмом за каждую
  // выкатку — быстрый способ научиться не читать эти письма.
  if (snapshot === null) return 'unknown'
  if (snapshot.utilization >= EVENT_LOOP_CRITICAL_UTILIZATION) return 'critical'
  if (snapshot.p99Ms >= EVENT_LOOP_CRITICAL_MS) return 'critical'
  if (snapshot.utilization >= EVENT_LOOP_WARN_UTILIZATION) return 'warn'
  if (snapshot.p99Ms >= EVENT_LOOP_WARN_MS) return 'warn'
  return 'ok'
}

/** Только для тестов: гистограмма и окно — состояние уровня модуля, и без
 *  сброса один тест диктовал бы результат следующему. */
export function _resetEventLoopMonitor(): void {
  histogram?.disable()
  histogram = null
  lastWindow = null
  worstMs = 0
  previousUtilization = null
}
