// Teacher strokes and dries; a joiner arriving at once must get the paper_dry.
import { createRequire } from 'node:module'
import { execFileSync } from 'node:child_process'
const { chromium } = createRequire('/home/suselman/projects/pencil-agents/watercolor-feel/package.json')('playwright')
const browser = await chromium.launch({ headless: true, args: ['--ignore-certificate-errors', '--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] })
const ctx = await browser.newContext({ ignoreHTTPSErrors: true, viewport: { width: 1600, height: 1000 } })
const A = await ctx.newPage()
await A.goto('https://localhost:5277/create')
await A.locator('form input[type="text"]').first().fill('teacher')
await A.locator('form button[type="submit"]').click()
await A.waitForURL(/\/room\/[^/]+$/)
await A.waitForFunction(() => !!window.__engine && getComputedStyle(document.querySelector('canvas')).pointerEvents !== 'none', undefined, { timeout: 60000 })
await A.waitForTimeout(1500)
await A.getByRole('button', { name: 'Drawing tool' }).first().click(); await A.waitForTimeout(300)
await A.getByText(/^Watercolor$|^Акварель$/).first().click(); await A.waitForTimeout(300); await A.keyboard.press('Escape')
const box = await A.locator('canvas').first().boundingBox()
await A.mouse.move(box.x + 300, box.y + 300); await A.mouse.down(); await A.mouse.move(box.x + 700, box.y + 320, { steps: 30 }); await A.mouse.up()
await A.waitForTimeout(1500)
const t = Date.now()
await A.getByRole('button', { name: /Dry everything|Высушить всё/ }).click()
await A.waitForTimeout(500)
const room = A.url().split('/').pop()
await browser.close()
console.log('dried; joining', room, 'after', Date.now() - t, 'ms')
console.log(execFileSync('node', ['joinprobe.mjs', room], { encoding: 'utf8' }).trim(), ' joined within', Math.round((Date.now() - t) / 1000), 's')
