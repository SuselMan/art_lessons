import { createRequire } from 'node:module'
const { chromium } = createRequire('/home/suselman/projects/pencil-agents/watercolor-feel/package.json')('playwright')
const browser = await chromium.launch({ headless: false, channel: 'chrome', args: ['--ignore-certificate-errors'] })
const page = await (await browser.newContext({ ignoreHTTPSErrors: true })).newPage()
page.on('console', m => { if (m.type() === 'error') console.log('console', m.text().slice(0, 300)) })
page.on('pageerror', e => console.log('pageerror', e.message.slice(0, 300)))
const t = Date.now()
await page.goto('https://localhost:5277/create'); console.log('goto', Date.now() - t)
await page.locator('form input[type="text"]').first().fill('rig')
await page.locator('form button[type="submit"]').click()
await page.waitForURL(/\/room\//, { timeout: 30000 }); console.log('room', Date.now() - t)
await page.waitForFunction(() => !!window.__engine, undefined, { timeout: 60000 }).catch(e => console.log('no engine', e.message.slice(0, 80)))
console.log('engine', Date.now() - t)
await page.waitForTimeout(1500)
await page.evaluate(() => { const e = window.__engine; e.setTool('watercolor'); e.setPencil('normal:100:100:PB29:round'); e.setColor([0.16, 0.23, 0.59]); e.setSize(12) })
const box = await page.locator('canvas').first().boundingBox()
await page.mouse.move(box.x + 300, box.y + 500); await page.mouse.down()
const steps = +(process.env.N || 300)
for (let i = 1; i <= steps; i++) { await Promise.race([page.mouse.move(box.x + 300 + i * 3, box.y + 500 + (i % 7)), new Promise(r => setTimeout(() => r('slow'), 5000))]).then(v => { if (v === 'slow') console.log('move stuck at', i) }); if (i % 100 === 0) console.log('moved', i, Date.now() - t) }
await Promise.race([page.mouse.up(), new Promise(r => setTimeout(r, 5000))]); console.log('up', Date.now() - t)
console.log('ops', await Promise.race([page.evaluate(() => window.__engine.getOperations().length), new Promise(r => setTimeout(() => r('eval stuck'), 10000))]))
await browser.close()
